/* Earthy's guided walkthrough. Runs when the page is opened with ?tour=earthy.
   The timeline (window.PIF_TOUR) is generated by tools/build-earthy-video.mjs from the voice clips' real durations. */
(() => {
  const params = new URLSearchParams(location.search);
  if (params.get("tour") !== "earthy") return;
  const T = window.PIF_TOUR; if (!T) { console.warn("no timeline"); return; }
  document.body.classList.add("is-tour");
  const $ = (s, r = document) => r.querySelector(s);

  const layer = document.createElement("div"); layer.className = "e-layer";
  layer.innerHTML = `
    <div class="e-focus" id="e-focus"></div>
    <svg class="e-cursor" id="e-cursor" viewBox="0 0 26 32"><path d="M2 2l20 15-9 1.5 5 10-4 2-5-10-7 6z" fill="#fff" stroke="#000" stroke-width="2" stroke-linejoin="round"/></svg>
    <div class="e-host" id="e-host">
      <svg class="earthy" id="earthy" viewBox="0 0 200 200" data-mood="neutral" data-gesture="none" aria-hidden="true">
        <defs>
          <radialGradient id="e-sea" cx="36%" cy="30%" r="80%"><stop offset="0" stop-color="#7fdcff"/><stop offset="1" stop-color="#1e8fe6"/></radialGradient>
          <clipPath id="e-clip"><circle cx="100" cy="104" r="72"/></clipPath>
        </defs>
        <g class="e-hand e-hand--l"><path class="e-arm" d="M50 130 Q32 142 30 162"/><circle class="e-palm" cx="30" cy="164" r="11"/><path class="e-spark" d="M12 122l-7-10M20 112l-2-12M6 136l-12-3"/></g>
        <g class="e-body">
          <circle class="e-skin" cx="100" cy="104" r="72"/>
          <g class="e-land" clip-path="url(#e-clip)">
            <path d="M58 38c16-12 38-8 46 4 6 9-4 19-16 20-11 2-25 10-32 1-6-7-7-18 2-25z"/>
            <path d="M122 66c14-7 32-2 38 11 6 11 1 28-9 36-9 7-20 2-24-9-4-11-16-30-5-38z"/>
            <path d="M40 98c11-5 24 2 26 15 2 13-6 28-19 32-11 4-22-6-22-19 0-13 4-23 15-28z"/>
            <path d="M84 142c11-9 28-7 36 4 6 9 2 24-9 30-13 7-30 4-34-9-2-11 0-19 7-25z"/>
            <path d="M134 152c8-5 19 0 21 8 2 9-6 15-15 13-9-2-13-15-6-21z"/>
            <path d="M100 30c6-2 12 2 11 7-1 5-8 7-13 4-4-3-3-9 2-11z"/>
          </g>
          <circle class="e-rim" cx="100" cy="104" r="72"/>
          <path class="e-brow e-brow--l" d="M70 72 L88 78"/><path class="e-brow e-brow--r" d="M130 72 L112 78"/>
          <g class="e-eyes">
            <g><ellipse class="e-eye" cx="84" cy="97" rx="9" ry="13"/><circle class="e-glint" cx="88" cy="91" r="3.2"/></g>
            <g><ellipse class="e-eye e-eye--r" cx="120" cy="97" rx="9" ry="13"/><circle class="e-glint e-glint--r" cx="124" cy="91" r="3.2"/><path class="e-wink" d="M110 97 Q120 87 130 97"/></g>
          </g>
          <circle class="e-cheek" cx="66" cy="114" r="7"/><circle class="e-cheek" cx="138" cy="114" r="7"/>
          <path class="e-mouth" id="e-mouth" d="M92 118 Q102 128 112 118"/>
        </g>
        <g class="e-hand e-hand--r"><path class="e-arm" d="M150 130 Q168 142 170 162"/><circle class="e-palm" cx="170" cy="164" r="11"/><path class="e-spark" d="M188 122l7-10M180 112l2-12M194 136l12-3"/></g>
      </svg>
      <div class="e-bubble" id="e-bubble"></div>
    </div>`;
  document.body.appendChild(layer);
  const host = $("#e-host"), earthy = $("#earthy"), mouth = $("#e-mouth"), bubble = $("#e-bubble"), focus = $("#e-focus"), cursor = $("#e-cursor");
  const MOUTH = { neutral: "M92 118 Q102 128 112 118", concerned: "M93 122 Q102 117 111 122", glad: "M88 116 Q102 134 116 116", talk: "M93 118 Q102 130 111 118 Q102 124 93 118" };

  /* --- primitives --- */
  const vw = () => innerWidth, vh = () => innerHeight;
  function moveEarthy(fx, fy) { host.style.transform = `translate(${Math.round(fx * vw())}px, ${Math.round(fy * vh())}px)`; }
  function face(mood, gesture) { earthy.dataset.mood = mood; mouth.setAttribute("d", MOUTH[mood] || MOUTH.neutral); earthy.dataset.gesture = "none"; void earthy.getBoundingClientRect(); earthy.dataset.gesture = gesture; }
  let blinkT; function blink() { clearTimeout(blinkT); blinkT = setTimeout(() => { earthy.classList.add("is-blinking"); setTimeout(() => earthy.classList.remove("is-blinking"), 200); blink(); }, 2200 + Math.random() * 3200); }
  let talkT; function talkFor(ms) { clearInterval(talkT); let open = false; const m = earthy.dataset.mood; talkT = setInterval(() => { open = !open; mouth.setAttribute("d", open ? MOUTH.talk : MOUTH[m] || MOUTH.neutral); }, 170); setTimeout(() => { clearInterval(talkT); mouth.setAttribute("d", MOUTH[m] || MOUTH.neutral); }, ms); }
  let typeT; function say(text, ms) {
    clearTimeout(typeT); bubble.classList.remove("is-done"); bubble.classList.add("is-on");
    bubble.innerHTML = '<span class="t"></span><span class="caret"></span>';
    const t = $(".t", bubble); const per = Math.max(14, Math.min(42, (ms * 0.82) / text.length)); let i = 0;
    const step = () => { i++; t.textContent = text.slice(0, i); if (i < text.length) typeT = setTimeout(step, per); else bubble.classList.add("is-done"); };
    step();
  }
  function hush() { bubble.classList.remove("is-on"); }
  function focusOn(sel, pad = 10) {
    const el = sel && $(sel); if (!el) { focus.classList.remove("is-on"); return; }
    const r = el.getBoundingClientRect();
    focus.style.width = (r.width + pad * 2) + "px"; focus.style.height = (r.height + pad * 2) + "px";
    focus.style.transform = `translate(${r.left - pad}px, ${r.top - pad}px)`; focus.classList.add("is-on");
  }
  function cursorTo(sel, show = true) {
    const el = sel && $(sel); if (!el) { cursor.classList.remove("is-on"); return; }
    const r = el.getBoundingClientRect(); const x = r.left + r.width * 0.5, y = r.top + r.height * 0.55;
    cursor.style.setProperty("--cur", `translate(${x}px, ${y}px)`); cursor.style.transform = `translate(${x}px, ${y}px)`; cursor.classList.toggle("is-on", show);
  }
  function click(sel) { const el = $(sel); if (!el) return; cursor.classList.remove("is-click"); void cursor.offsetWidth; cursor.classList.add("is-click"); el.classList.add("e-tap"); setTimeout(() => el.classList.remove("e-tap"), 400); el.click(); }
  let scrollAnim; function scrollToSel(sel, offset = 120, ms = 1300) {
    cancelAnimationFrame(scrollAnim);
    const el = $(sel); const target = el ? Math.max(0, Math.min(document.documentElement.scrollHeight - vh(), el.getBoundingClientRect().top + scrollY - offset)) : 0;
    const from = scrollY, t0 = performance.now(); const ease = t => t < .5 ? 4 * t * t * t : 1 - Math.pow(-2 * t + 2, 3) / 2;
    const tick = now => { const p = Math.min(1, (now - t0) / ms); scrollTo(0, from + (target - from) * ease(p)); if (p < 1) scrollAnim = requestAnimationFrame(tick); };
    scrollAnim = requestAnimationFrame(tick);
  }
  function carouselDrift(ms) { const c = $("#carousel"); if (!c) return; const from = c.scrollLeft, to = from + 760, t0 = performance.now(); const tick = now => { const p = Math.min(1, (now - t0) / ms); c.scrollLeft = from + (to - from) * (1 - Math.pow(1 - p, 3)); if (p < 1) requestAnimationFrame(tick); }; requestAnimationFrame(tick); }
  // keep the focus ring glued to its target while the page scrolls
  let focusSel = null; (function track() { if (focusSel) focusOn(focusSel); requestAnimationFrame(track); })();

  /* --- runner --- */
  const timers = [];
  const at = (ms, fn) => timers.push(setTimeout(fn, ms));
  function run() {
    blink(); earthy.classList.add("is-alive"); moveEarthy(T.steps[0].x, T.steps[0].y);
    T.steps.forEach(s => {
      at(s.at * 1000, () => {
        if (s.scroll) scrollToSel(s.scroll, s.offset ?? 120, s.scrollMs ?? 1300);
        moveEarthy(s.x, s.y); face(s.mood || "neutral", s.gesture || "point");
        if (s.walk) { face(s.mood || "neutral", "walk"); setTimeout(() => face(s.mood || "neutral", s.gesture || "point"), 1000); }
        setTimeout(() => { focusSel = s.target || null; if (!focusSel) focus.classList.remove("is-on"); }, s.scroll ? 700 : 120);
        say(s.say, s.dur * 1000); talkFor(s.dur * 1000);
        (s.actions || []).forEach(a => at((s.at + a.at) * 1000, () => {
          if (a.type === "cursor") cursorTo(a.sel);
          if (a.type === "click") { cursorTo(a.sel); setTimeout(() => click(a.sel), 420); }
          if (a.type === "hide-cursor") cursor.classList.remove("is-on");
          if (a.type === "focus") focusSel = a.sel;
          if (a.type === "carousel") carouselDrift(a.ms || 2600);
        }));
      });
    });
    at((T.end) * 1000, () => { hush(); focusSel = null; focus.classList.remove("is-on"); cursor.classList.remove("is-on"); });
  }
  window.PIF_TOUR_START = run;
  if (!params.has("wait")) addEventListener("load", () => setTimeout(run, 800));
})();
